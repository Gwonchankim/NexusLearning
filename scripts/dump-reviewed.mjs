// Local helper: dump approved problems (reviewed=true) to supabase/seed_problems.sql
// so `npm run db:reset` reproduces the reviewed baseline (Option C).
// Requires the SERVICE_ROLE key: since migration 0006, answer/solution/
// wrong_feedback are NOT readable with the anon key (the public surface is the
// problems_public view, which omits them), so dumping the full seed needs the
// privileged key. Keep it server-only — never commit it.
// Env:
//   SUPABASE_URL (default http://127.0.0.1:54321)
//   SUPABASE_SERVICE_ROLE_KEY (required)
//
// Usage:
//   $env:SUPABASE_SERVICE_ROLE_KEY="..."; node scripts/dump-reviewed.mjs
import { writeFile } from 'node:fs/promises'
import { fileURLToPath } from 'node:url'
import { dirname, join } from 'node:path'

const BASE = process.env.SUPABASE_URL || process.env.NEXT_PUBLIC_SUPABASE_URL || 'http://127.0.0.1:54321'
const KEY = process.env.SUPABASE_SERVICE_ROLE_KEY

if (!KEY) {
  console.error(
    'Missing env: SUPABASE_SERVICE_ROLE_KEY (required).\n' +
      'Since migration 0006, answer/solution/wrong_feedback are not readable with the\n' +
      'anon key — dumping the seed needs the service_role key (server-only, never commit).',
  )
  process.exit(1)
}

const cols = 'import_key,concept_id,stem,choices,answer,solution,wrong_feedback,difficulty,answer_type,source'
const res = await fetch(
  `${BASE}/rest/v1/problems?select=${cols}&reviewed=eq.true&order=concept_id,import_key`,
  { headers: { apikey: KEY, Authorization: `Bearer ${KEY}` } },
)
const rows = await res.json()
if (!Array.isArray(rows)) {
  console.error('fetch failed:', JSON.stringify(rows))
  process.exit(1)
}

const q = (v) => (v == null ? 'null' : `'${String(v).replace(/'/g, "''")}'`)
const jb = (v) => (v == null ? 'null' : `'${JSON.stringify(v).replace(/'/g, "''")}'::jsonb`)

const values = rows
  .map(
    (r) =>
      `  (${q(r.import_key)}, ${q(r.concept_id)}, ${q(r.stem)}, ${jb(r.choices)}, ${q(r.answer)}, ` +
      `${q(r.solution)}, ${q(r.wrong_feedback)}, ${q(r.difficulty)}, ${q(r.answer_type)}, ${q(r.source)}, true, null, now())`,
  )
  .join(',\n')

const body =
  rows.length === 0
    ? '-- (no reviewed problems)'
    : `insert into public.problems
  (import_key, concept_id, stem, choices, answer, solution, wrong_feedback, difficulty, answer_type, source, reviewed, reviewer_id, reviewed_at)
values
${values}
on conflict (import_key) do nothing;`

const sql = `-- seed_problems.sql
-- GENERATED by scripts/dump-reviewed.mjs — do not edit by hand.
-- Approved problems (reviewed=true) captured for reproducible \`db:reset\` (PR2 Option C).
-- source is preserved from review; reviewer_id is null (seeded, not a runtime user).

${body}
`

const out = join(dirname(fileURLToPath(import.meta.url)), '..', 'supabase', 'seed_problems.sql')
await writeFile(out, sql, 'utf8')
console.log(`wrote ${rows.length} reviewed problem(s) to supabase/seed_problems.sql`)
